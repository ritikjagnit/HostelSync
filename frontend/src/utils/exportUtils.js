/**
 * Export Utilities for HostelSync
 * Provides client-side Excel (.xls) and CSV generation with institutional styling.
 */

/**
 * Downloads a formatted Excel workbook (.xls) with custom styling, headers, and metadata.
 * Works natively in Microsoft Excel, LibreOffice Calc, and Google Sheets.
 */
export function downloadExcel(filename, title, category, headers, rows, summaryStats = []) {
  const safeFilename = filename.endsWith('.xls') ? filename : `${filename}.xls`;
  const dateStr = new Date().toLocaleString('en-IN');

  let statsHtml = '';
  if (summaryStats.length > 0) {
    statsHtml = `
      <tr>
        <td colspan="${headers.length}" style="background-color: #f1f5f9; padding: 8px; font-size: 11px; border: 1px solid #cbd5e1;">
          <strong>Executive Summary:</strong> ${summaryStats.map((s) => `${s.label}: <strong>${s.value}</strong>`).join(' &nbsp;|&nbsp; ')}
        </td>
      </tr>
      <tr><td colspan="${headers.length}"></td></tr>
    `;
  }

  const theadHtml = headers
    .map((h) => `<th style="background-color: #0b192c; color: #ffffff; font-weight: bold; padding: 8px 10px; border: 1px solid #334155; font-size: 11px; text-transform: uppercase;">${escapeHtml(h)}</th>`)
    .join('');

  const tbodyHtml = rows
    .map((row, idx) => {
      const bg = idx % 2 === 0 ? '#ffffff' : '#f8fafc';
      const cells = row
        .map((cell) => `<td style="padding: 6px 10px; border: 1px solid #e2e8f0; font-size: 11px; background-color: ${bg};">${escapeHtml(String(cell != null ? cell : ''))}</td>`)
        .join('');
      return `<tr>${cells}</tr>`;
    })
    .join('');

  const html = `
    <html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel" xmlns="http://www.w3.org/TR/REC-html40">
    <head>
      <!--[if gte mso 9]>
      <xml>
        <x:ExcelWorkbook>
          <x:ExcelWorksheets>
            <x:ExcelWorksheet>
              <x:Name>${escapeHtml(title.slice(0, 31))}</x:Name>
              <x:WorksheetOptions>
                <x:DisplayGridlines/>
              </x:WorksheetOptions>
            </x:ExcelWorksheet>
          </x:ExcelWorksheets>
        </x:ExcelWorkbook>
      </xml>
      <![endif]-->
      <meta http-equiv="content-type" content="text/plain; charset=UTF-8"/>
      <style>
        body { font-family: Calibri, 'Segoe UI', Arial, sans-serif; }
        table { border-collapse: collapse; width: 100%; }
      </style>
    </head>
    <body>
      <table>
        <tr>
          <td colspan="${headers.length}" style="font-size: 14px; font-weight: bold; color: #0b192c; padding: 6px 0;">
            GOVERNMENT POLYTECHNIC SAKOLI &bull; DIRECTORATE OF TECHNICAL EDUCATION, MAHARASHTRA
          </td>
        </tr>
        <tr>
          <td colspan="${headers.length}" style="font-size: 12px; font-weight: bold; color: #0284c7; padding-bottom: 4px;">
            ${escapeHtml(title.toUpperCase())} (${escapeHtml(category)})
          </td>
        </tr>
        <tr>
          <td colspan="${headers.length}" style="font-size: 10px; color: #64748b; padding-bottom: 10px;">
            DTE Code: 04008 | Generated on: ${dateStr} | Confidential Institutional Record
          </td>
        </tr>
        ${statsHtml}
        <thead>
          <tr>${theadHtml}</tr>
        </thead>
        <tbody>
          ${tbodyHtml}
        </tbody>
        <tfoot>
          <tr><td colspan="${headers.length}"></td></tr>
          <tr>
            <td colspan="${headers.length}" style="font-size: 9px; color: #94a3b8; padding-top: 10px;">
              * Official hostel audit transcript automatically generated by HostelSync Residential Management System.
            </td>
          </tr>
        </tfoot>
      </table>
    </body>
    </html>
  `;

  const blob = new Blob([html], { type: 'application/vnd.ms-excel;charset=utf-8;' });
  triggerDownload(blob, safeFilename);
}

/**
 * Downloads standard CSV with UTF-8 BOM.
 */
export function downloadCsv(filename, headers, rows) {
  const safeFilename = filename.endsWith('.csv') ? filename : `${filename}.csv`;
  const escapeCsv = (val) => {
    if (val == null) return '';
    const str = String(val);
    if (str.includes(',') || str.includes('"') || str.includes('\n')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };

  const lines = [
    headers.map(escapeCsv).join(','),
    ...rows.map((row) => row.map(escapeCsv).join(','))
  ];

  const csvContent = '\uFEFF' + lines.join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  triggerDownload(blob, safeFilename);
}

/**
 * Parses raw CSV string into { headers, rows }.
 */
export function parseCsv(csvText) {
  if (!csvText || !csvText.trim()) return { headers: [], rows: [] };
  const lines = csvText.split(/\r?\n/).filter((line) => line.trim().length > 0);
  if (lines.length === 0) return { headers: [], rows: [] };

  const parseLine = (line) => {
    const result = [];
    let current = '';
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const char = line[i];
      if (char === '"') {
        if (inQuotes && line[i + 1] === '"') {
          current += '"';
          i++;
        } else {
          inQuotes = !inQuotes;
        }
      } else if (char === ',' && !inQuotes) {
        result.push(current.trim());
        current = '';
      } else {
        current += char;
      }
    }
    result.push(current.trim());
    return result;
  };

  const headers = parseLine(lines[0]);
  const rows = lines.slice(1).map(parseLine);
  return { headers, rows };
}

function escapeHtml(str) {
  if (str == null) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

function triggerDownload(blob, filename) {
  const url = window.URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  setTimeout(() => {
    window.URL.revokeObjectURL(url);
    document.body.removeChild(a);
  }, 100);
}

